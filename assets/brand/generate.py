"""Regenerates every Enclavier icon from logo-source.png (needs Pillow and numpy).

    python assets/brand/generate.py

The source artwork is drawn on white. The white is removed (each pixel is
treated as colour over white), and the mark is placed on a dark tile, so the
logo is never shown on a white or light background.

Outputs (committed, so builds don't need Python):
    icon-<size>.png   the mark on a dark rounded tile, transparent corners
    mark.png          the mark alone on a transparent background
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

here = Path(__file__).parent
TILE = (10, 22, 48)  # deep navy behind the mark

# Un-mix the white background into transparency.
rgb = np.asarray(Image.open(here / "logo-source.png").convert("RGB")).astype(np.float32) / 255
alpha = 1 - rgb.min(axis=2)
a = np.clip(alpha, 1e-4, 1)[..., None]
colour = np.clip((rgb - (1 - a)) / a, 0, 1)
mark = Image.fromarray((np.dstack([colour, alpha[..., None]]) * 255).round().astype(np.uint8), "RGBA")

# Crop to the artwork and square it (transparent padding).
left, top, right, bottom = mark.point(lambda v: 255 if v > 10 else 0).getbbox()
side = max(right - left, bottom - top)
square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
square.paste(mark.crop((left, top, right, bottom)), ((side - (right - left)) // 2, (side - (bottom - top)) // 2))
square.resize((512, 512), Image.LANCZOS).save(here / "mark.png", optimize=True)

SCALE = 4       # supersampling for smooth corners
FILL = 0.78     # how much of the tile the mark covers
RADIUS = 0.22   # corner radius as a share of the tile

for size in (16, 32, 48, 64, 128, 256, 512):
    big = size * SCALE
    tile = Image.new("RGBA", (big, big), TILE + (255,))
    inner = round(big * FILL)
    tile.alpha_composite(square.resize((inner, inner), Image.LANCZOS), ((big - inner) // 2, (big - inner) // 2))
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, big - 1, big - 1), radius=round(big * RADIUS), fill=255)
    tile.putalpha(mask)
    tile.resize((size, size), Image.LANCZOS).save(here / f"icon-{size}.png", optimize=True)
    print(f"icon-{size}.png")

# Copies for places that can't read this folder at build time.
import base64, shutil

repo = here.parent.parent
shutil.copy(here / "icon-128.png", repo / "apps" / "web" / "public" / "logo.png")
shutil.copy(here / "icon-64.png", repo / "apps" / "web" / "public" / "favicon.png")
b64 = base64.b64encode((here / "icon-128.png").read_bytes()).decode()
(repo / "apps" / "server" / "src" / "brandLogo.ts").write_text(
    "// Generated by assets/brand/generate.py. The logo embedded in e-mails (inline attachment).\n"
    f"export const BRAND_LOGO_PNG = Buffer.from('{b64}', 'base64');\n",
    encoding="utf8",
    newline="\n",
)
print("web logo, favicon and server e-mail logo updated")
